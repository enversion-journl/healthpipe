_VALID_SQL_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _validate_identifier(identifier: str) -> str:
    """Validate that an identifier contains only safe characters.

    Used for operator-supplied values (e.g. ``RunModeConfig.delta_column``)
    before interpolating them into Oracle SQL.  Does NOT add quoting —
    Oracle identifiers in this codebase are uppercase and unquoted.
    """
    cleaned = identifier.replace("[", "").replace("]", "")
    if not _VALID_SQL_IDENTIFIER.match(cleaned):
        raise ValueError(
            f"Invalid SQL identifier: {identifier!r}. "
            f"Only alphanumeric characters and underscores are allowed."
        )
    return cleaned


def _validate_table_ref(qualified_name: str) -> str:
    """Validate a ``SCHEMA.TABLE`` Oracle table reference.

    Each component must be a valid SQL identifier.  Returns the cleaned
    form without quoting (Oracle convention in this codebase).
    """
    cleaned = qualified_name.replace("[", "").replace("]", "")
    parts = cleaned.split(".")
    if len(parts) not in (1, 2):
        raise ValueError(
            f"Invalid table reference: {qualified_name!r}. " f"Expected 'SCHEMA.TABLE' or 'TABLE'."
        )
    for part in parts:
        if not _VALID_SQL_IDENTIFIER.match(part):
            raise ValueError(
                f"Invalid identifier in table reference: {part!r} "
                f"(from {qualified_name!r}). "
                f"Only alphanumeric characters and underscores are allowed."
            )
    return ".".join(parts)


