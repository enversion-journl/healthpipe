def _full_load_config(table: str) -> ArchiveMergeConfig:
    """Return an ArchiveMergeConfig for a full-load ILS table."""
    return ArchiveMergeConfig(
        source_schema="ext",
        source_table=f"{table}_ils_dfm",
        target_schema="arc",
        target_table=f"{table}_ils",
        merge_keys=("prrowid",),
        non_key_columns=_NON_KEY_COLUMNS[table],
        strategy="upsert",
        update_only_on_change=True,
        detect_deletes=False,
        upstream_is_full_load=True,
    )


