def _normalize_checkpoint(checkpoint: str) -> str:
    """Strip fractional seconds from a checkpoint string.

    MSSQL checkpoints may look like '2021-01-01 00:00:00.000000' or
    '2025-05-08 10:30:45.123'. We truncate to 'YYYY-MM-DD HH:MI:SS'
    for Oracle TO_DATE comparison, which works against both DATE and
    TIMESTAMP columns (Oracle does implicit TIMESTAMP→DATE comparison).
    """
    cp = checkpoint.strip()
    dot_pos = cp.find(".")
    if dot_pos > 0:
        cp = cp[:dot_pos]
    return cp


def build_oracle_where(
    run_config: RunModeConfig,
    checkpoint: str | None,
    extract_config: DfmExtractConfig,
    upper_bound: str | None = None,
) -> str | None:
    """Build an Oracle WHERE clause driven by RunModeConfig + DfmExtractConfig.

    Generic for any Oracle source table.  The delta column/expression comes
    from the shared DfmExtractConfig.  RunModeConfig.delta_column can
    override it at run time.

    Args:
        run_config: Run-time config controlling mode and overrides.
        checkpoint: Lower-bound checkpoint (exclusive).  Typically
            MAX(delta_column) from the previous archive merge.
        extract_config: Design-time extraction config providing delta_column,
            lookback_days, is_full_load, etc.
        upper_bound: Optional upper-bound checkpoint (inclusive).
            When provided, the WHERE becomes:
              delta_column > checkpoint AND upper_bound_col <= upper_bound
            where upper_bound_col is extract_config.upper_bound_column if set,
            otherwise falls back to the delta column.
            This prevents extracting rows that arrived after the flow
            started, ensuring consistent delta windows across tables.
    """
    if run_config.delta_column:
        col: str | None = _validate_identifier(run_config.delta_column)
    else:
        col = extract_config.effective_delta_col

    if run_config.mode == "full_load" or extract_config.is_full_load:
        return None

    if run_config.mode == "delta":
        clauses: list[str] = []
        if checkpoint:
            validate_checkpoint_value(checkpoint)
            cp_val = _normalize_checkpoint(checkpoint)
            lookback = run_config.lookback_days or extract_config.lookback_days or 0
            if lookback > 0:
                clauses.append(
                    f"{col} > (TO_DATE('{cp_val}', "
                    f"'YYYY-MM-DD HH24:MI:SS') "
                    f"- INTERVAL '{lookback}' DAY)"
                )
            else:
                clauses.append(f"{col} > TO_DATE('{cp_val}', 'YYYY-MM-DD HH24:MI:SS')")
        if upper_bound:
            validate_checkpoint_value(upper_bound)
            ub_col = extract_config.upper_bound_column or col
            ub_val = _normalize_checkpoint(upper_bound)
            clauses.append(
                f"({ub_col} <= TO_DATE('{ub_val}', 'YYYY-MM-DD HH24:MI:SS') OR {ub_col} IS NULL)"
            )
        return " AND ".join(clauses) if clauses else None

    if run_config.mode == "period":
        safe_from = cast(str, run_config.date_from).replace("'", "''")
        if run_config.date_to:
            safe_to = run_config.date_to.replace("'", "''")
            return (
                f"{col} >= TO_DATE('{safe_from}', 'YYYY-MM-DD') "
                f"AND {col} < TO_DATE('{safe_to}', 'YYYY-MM-DD') + 1"
            )
        return f"{col} >= TO_DATE('{safe_from}', 'YYYY-MM-DD')"

    if run_config.mode == "ids":
        id_col = _validate_identifier(run_config.id_filter_column or "OBJECT_ID")
        if run_config.id_filter_table:
            safe_tbl = _validate_table_ref(run_config.id_filter_table)
            # Alias + qualify the subquery column: if id_filter_column doesn't exist
            # in the filter table, Oracle fails loudly instead of silently
            # correlating to the outer table (always-true → full extract).
            return f"{id_col} IN (SELECT flt.{id_col} FROM {safe_tbl} flt)"
        escaped = ", ".join(
            f"'{v.replace(chr(39), chr(39) * 2)}'"
            for v in cast(list[str], run_config.id_filter_values)
        )
        return f"{id_col} IN ({escaped})"

    return None


