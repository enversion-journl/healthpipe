# Job types in one finished cycle can end seconds apart; cycles are at least 4 h apart.
IFDB_CYCLE_MAX_SPREAD = timedelta(hours=1)
IFDB_CYCLE_POLL_SECONDS = 60
# The patient job sets IGANG under a second after hh:00 and the rest follow within ~9 s.
IFDB_CYCLE_CONFIRM_SECONDS = 15
# Every job type starts within seconds of hh:00, so a lagging type that is not running by now failed.
IFDB_CYCLE_FAILED_AFTER = timedelta(minutes=15)


@dataclass(frozen=True)
class IFDBCycleState:
    flow_start: datetime | None
    lagging_job_types: tuple[str, ...]
    running_job_types: tuple[str, ...]
    failed_job_types: tuple[str, ...] = ()

    @property
    def is_complete(self) -> bool:
        return not self.lagging_job_types and not self.running_job_types


def ifdb_cycle_state(rows: list[tuple[str, datetime, int | None]], now: datetime) -> IFDBCycleState:
    """Summarise (JOBTYPE, MAX(SLUTTID), IGANG) rows at Oracle time `now` into the cycle state."""
    if not rows:
        return IFDBCycleState(None, (), ())
    newest = max(end for _, end, _ in rows)
    lagging = tuple(sorted(job for job, end, _ in rows if newest - end >= IFDB_CYCLE_MAX_SPREAD))
    running = tuple(sorted(job for job, _, is_running in rows if is_running == 1))
    return IFDBCycleState(
        flow_start=min(end for _, end, _ in rows),
        lagging_job_types=lagging,
        running_job_types=running,
        failed_job_types=(
            lagging if not running and now - newest > IFDB_CYCLE_FAILED_AFTER else ()
        ),
    )


def _read_ifdb_cycle_rows(
    ifdb_oracle: IFDBOracleResource,
) -> tuple[list[tuple[str, datetime, int | None]], datetime]:
    bind_list = ", ".join(f":{i}" for i in range(len(IFDB_ACTIVE_JOB_TYPES)))
    sql = f"""
        SELECT l.JOBTYPE, l.LAST_SLUTTID, s.IGANG
        FROM (
            SELECT JOBTYPE, MAX(SLUTTID) AS LAST_SLUTTID
            FROM IFDB.JOB_LOG
            WHERE SUCCES = 1
                AND SLUTTID IS NOT NULL
                AND JOBTYPE IN ({bind_list})
            GROUP BY JOBTYPE
        ) l
        LEFT JOIN IFDB.JOB_STATUS s ON s.JOBTYPE = l.JOBTYPE
    """
    with ifdb_oracle.get_connection() as ora_conn:
        ora_cursor = ora_conn.cursor()
        try:
            # SYSDATE before the job read: a job still writing rows stamped before it shows IGANG.
            ora_cursor.execute("SELECT SYSDATE FROM DUAL")
            now = ora_cursor.fetchone()[0]
            ora_cursor.execute(sql, list(IFDB_ACTIVE_JOB_TYPES))
            return ora_cursor.fetchall(), now
        finally:
            ora_cursor.close()


def wait_for_complete_ifdb_cycle(
    context: dg.AssetExecutionContext,
    ifdb_oracle: IFDBOracleResource,
    timeout_minutes: int,
) -> IFDBCycleState:
    """Wait for two reads that agree on a complete cycle; return at once without JOB_LOG rows."""
    deadline = time.monotonic() + timeout_minutes * 60
    rows, now = _read_ifdb_cycle_rows(ifdb_oracle)
    missing = sorted(set(IFDB_ACTIVE_JOB_TYPES) - {job for job, _, _ in rows})
    no_status = sorted(job for job, _, running in rows if running is None)
    if missing or no_status:
        context.log.warning(
            "IFDB cycle check cannot see every active job type: "
            f"no successful JOB_LOG row={missing}, no JOB_STATUS.IGANG={no_status}"
        )
    candidate = None
    while True:
        state = ifdb_cycle_state(rows, now)
        if state.flow_start is None:
            return state
        if state.failed_job_types:
            raise dg.Failure(
                description=(
                    f"IFDB job types failed in IFDB: {list(state.failed_job_types)}. Their last "
                    "successful JOB_LOG row is from an earlier cycle and no job type is running. "
                    "Rerun when IFDB has run them again."
                )
            )
        if state.is_complete:
            if state.flow_start == candidate:
                return state
            candidate = state.flow_start
            context.log.info(f"IFDB cycle looks complete at {candidate}; confirming")
            pause = IFDB_CYCLE_CONFIRM_SECONDS
        else:
            candidate = None
            blocked_by = (
                f"lagging={list(state.lagging_job_types)}, "
                f"running={list(state.running_job_types)}"
            )
            if time.monotonic() >= deadline:
                raise dg.Failure(
                    description=(
                        f"IFDB cycle not complete after {timeout_minutes} min ({blocked_by}). "
                        "Rerun when IFDB has finished the cycle."
                    )
                )
            context.log.info(f"Waiting for a complete IFDB cycle: {blocked_by}")
            pause = IFDB_CYCLE_POLL_SECONDS
        time.sleep(pause)
        rows, now = _read_ifdb_cycle_rows(ifdb_oracle)


@dg.asset(
    name="dfm_ifdb_cycle_wait",
    group_name="ifdb_archive",
    compute_kind="oracle",
    tags={"domain": "ifdb", "layer": "dfm"},
    description=(
        "Wait until every active IFDB job type has finished the same IFDB cycle and none is "
        "running (JOB_LOG and JOB_STATUS.IGANG), confirmed by a second read. Fails at once when a "
        "job type failed in IFDB, and otherwise after cycle_wait_timeout_minutes; 0 turns the "
        "wait off and skips the IFDB read. Returns at once when JOB_LOG has no rows. Holds dfm_ifdb_flow_start, so "
        "the wait shows here and not in the extracts."
    ),
)
def dfm_ifdb_cycle_wait(
    context: dg.AssetExecutionContext,
    ifdb_oracle: IFDBOracleResource,
    config: IFDBCycleWaitConfig,
) -> dg.MaterializeResult:
    """Block until IFDB has finished a cycle, or JOB_LOG has no rows, and report the wait."""
    if config.cycle_wait_timeout_minutes == 0:
        context.log.info("cycle_wait_timeout_minutes is 0: not reading the IFDB cycle")
        return dg.MaterializeResult(metadata={"cycle_wait_seconds": 0, "complete": None})
    started = time.monotonic()
    state = wait_for_complete_ifdb_cycle(context, ifdb_oracle, config.cycle_wait_timeout_minutes)
    return dg.MaterializeResult(
        metadata={
            "cycle_wait_seconds": round(time.monotonic() - started),
            "complete": state.flow_start is not None,
            "flow_start": str(state.flow_start) if state.flow_start is not None else "",
        }
    )


@dg.asset(
    name="dfm_ifdb_flow_start",
    group_name="ifdb_archive",
    compute_kind="oracle",
    deps=["staging_infra_dfm", "dfm_ifdb_cycle_wait"],
    tags={"domain": "ifdb", "layer": "dfm"},
    description=(
        "Store the two ceilings the IFDB delta extracts in the same run read, "
        "after dfm_ifdb_cycle_wait, which waits for a complete IFDB cycle unless its timeout is "
        "0. The transfer ceiling is Oracle SYSDATE at a complete cycle and bounds the tables "
        "whose delta column IFDB stamps on transfer. The EPJ ceiling is MIN(MAX(SLUTTID)) "
        "across the active job types and bounds the tables that only carry the EPJ "
        "modification time. While a cycle is incomplete both stay at their previous values. "
        "flow_start_override sets both."
    ),
)
def dfm_ifdb_flow_start(
    context: dg.AssetExecutionContext,
    ifdb_oracle: IFDBOracleResource,
    mssql_target_staging: MSSQLResource,
    config: FlowStartConfig,
) -> dg.MaterializeResult:
    """Store the IFDB transfer ceiling and the EPJ ceiling as flow-start checkpoints."""
    dfm = DfmManager(mssql_target_staging, context)
    run_ctx = dfm.start_dfm_run(
        *IFDB_EPJ_CEILING,
        dagster_run_id=context.run_id,
        mode="flow_start",
        **({} if config.flow_start_override else resource_source(ifdb_oracle, "IFDB.JOB_LOG")),
    )

    epj_ceiling: str | None
    transfer_ceiling: str | None
    try:
        if config.flow_start_override:
            epj_ceiling = transfer_ceiling = config.flow_start_override
            source = "override"
            context.log.info(f"IFDB flow start OVERRIDE from run config: {epj_ceiling}")
        else:
            rows, now = _read_ifdb_cycle_rows(ifdb_oracle)
            state = ifdb_cycle_state(rows, now)
            if state.flow_start is not None:
                epj_ceiling = state.flow_start.strftime("%Y-%m-%d %H:%M:%S")
                source = "IFDB.JOB_LOG"
                if state.is_complete:
                    transfer_ceiling = now.strftime("%Y-%m-%d %H:%M:%S")
                else:
                    transfer_ceiling = dfm.get_checkpoint(*IFDB_TRANSFER_CEILING)
                    epj_ceiling = dfm.get_checkpoint(*IFDB_EPJ_CEILING) or epj_ceiling
                    blocked_by = (
                        f"lagging={list(state.lagging_job_types)}, "
                        f"running={list(state.running_job_types)}"
                    )
                    if transfer_ceiling is None:
                        raise dg.Failure(
                            description=(
                                f"IFDB cycle not complete at flow start ({blocked_by}) and no "
                                "earlier transfer ceiling to keep. Rerun when IFDB has "
                                "finished the cycle."
                            )
                        )
                    context.log.warning(
                        f"IFDB cycle not complete at flow start ({blocked_by}); keeping both "
                        f"ceilings: transfer={transfer_ceiling}, EPJ={epj_ceiling}"
                    )
                context.log.info(
                    f"IFDB ceilings from JOB_LOG/JOB_STATUS: transfer={transfer_ceiling}, "
                    f"EPJ={epj_ceiling}"
                )
            else:
                context.log.warning(
                    "IFDB.JOB_LOG/JOB_STATUS returned no rows or NULL — "
                    "falling back to MSSQL SYSDATETIME(). "
                    "This is expected in local dev but should not happen in production."
                )
                dfm.set_checkpoint(*IFDB_EPJ_CEILING, mode="flow_start")
                epj_ceiling = transfer_ceiling = dfm.get_checkpoint(*IFDB_EPJ_CEILING)
                source = "SYSDATETIME_fallback"

        dfm.set_checkpoint(*IFDB_EPJ_CEILING, value=epj_ceiling, mode="flow_start")
        dfm.set_checkpoint(*IFDB_TRANSFER_CEILING, value=transfer_ceiling, mode="flow_start")

        dfm.complete_dfm_run(run_ctx.log_id, checkpoint_after=epj_ceiling, rows_affected=0)

        return dg.MaterializeResult(
            metadata={
                "flow_start": epj_ceiling,
                "transfer_ceiling": transfer_ceiling,
                "source": source,
            }
        )
    except Exception as exc:
        dfm.fail_dfm_run(run_ctx.log_id, error_message=str(exc))
        raise


