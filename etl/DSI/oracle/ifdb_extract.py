DFM_IFDB_FLOW_SCHEMA = "dfm"
DFM_IFDB_FLOW_TABLE = "ifdb_flow_start"


@dg.asset(
    name="dfm_ifdb_flow_start",
    group_name="ifdb_archive",
    compute_kind="oracle",
    deps=["staging_infra_dfm"],
    tags={"domain": "ifdb", "layer": "dfm"},
    description=(
        "Capture MIN(MAX(SLUTTID)) across active IFDB job types as the "
        "upper bound before extraction. All delta extracts in the same "
        "run use this as their ceiling so that rows not yet processed by "
        "all IFDB jobs are excluded, preventing cross-table inconsistency."
    ),
)
def dfm_ifdb_flow_start(
    context: dg.AssetExecutionContext,
    ifdb_oracle: IFDBOracleResource,
    mssql_target_staging: MSSQLResource,
    config: FlowStartConfig,
) -> dg.MaterializeResult:
    """Fetch IFDB last-success timestamp and store it as the flow-start checkpoint."""
    dfm = DfmManager(mssql_target_staging, context)
    run_ctx = dfm.start_dfm_run(
        DFM_IFDB_FLOW_SCHEMA,
        DFM_IFDB_FLOW_TABLE,
        dagster_run_id=context.run_id,
        mode="flow_start",
    )

    try:
        if config.flow_start_override:
            flow_ts = config.flow_start_override
            source = "override"
            context.log.info(f"IFDB flow start OVERRIDE from run config: {flow_ts}")
        else:
            bind_list = ", ".join(f":{i}" for i in range(len(IFDB_ACTIVE_JOB_TYPES)))
            flow_start_sql = f"""
                SELECT MIN(last_job_end) FROM (
                    SELECT MAX(l.SLUTTID) AS last_job_end
                    FROM IFDB.JOB_LOG l
                    WHERE SUCCES = 1
                        AND l.JOBTYPE IN ({bind_list})
                    GROUP BY l.JOBTYPE
                )
            """
            with ifdb_oracle.get_connection() as ora_conn:
                ora_cursor = ora_conn.cursor()
                try:
                    ora_cursor.execute(flow_start_sql, list(IFDB_ACTIVE_JOB_TYPES))
                    row = ora_cursor.fetchone()
                finally:
                    ora_cursor.close()

            if row and row[0] is not None:
                flow_ts = row[0].strftime("%Y-%m-%d %H:%M:%S")
                source = "IFDB.JOB_LOG"
                context.log.info(f"IFDB flow start from JOB_LOG/JOB_STATUS: {flow_ts}")
            else:
                context.log.warning(
                    "IFDB.JOB_LOG/JOB_STATUS returned no rows or NULL — "
                    "falling back to MSSQL SYSDATETIME(). "
                    "This is expected in local dev but should not happen in production."
                )
                dfm.set_checkpoint(DFM_IFDB_FLOW_SCHEMA, DFM_IFDB_FLOW_TABLE, mode="flow_start")
                flow_ts = dfm.get_checkpoint(DFM_IFDB_FLOW_SCHEMA, DFM_IFDB_FLOW_TABLE)
                source = "SYSDATETIME_fallback"

        dfm.set_checkpoint(
            DFM_IFDB_FLOW_SCHEMA, DFM_IFDB_FLOW_TABLE, value=flow_ts, mode="flow_start"
        )

        dfm.complete_dfm_run(run_ctx.log_id, checkpoint_after=flow_ts, rows_affected=0)

        return dg.MaterializeResult(
            metadata={
                "flow_start": flow_ts,
                "source": source,
            }
        )
    except Exception as exc:
        dfm.fail_dfm_run(run_ctx.log_id, error_message=str(exc))
        raise


