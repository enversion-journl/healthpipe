"""Datasaet-specifikationer for DRG-grupperet LPR fra SDS.

EN kilde til sandhed for extract (DSI/csv_files/drg.py), arkiv
(DSI/csv_files/drg_archive.py) og arc-DDL
(infrastructure/ddl/tables/drg/00_archive.sql — genereret herfra og
holdt i sync af tests/unit/test_drg_datasets_ddl.py).

Kolonnerne er UNIONEN af SDS' egne Metadata_*-skemaer fra T24/T25/T26
(hoestet 2026-08-26; eneste forskel er tre T26-kolonner paa somatik-
kontakten og en paa forloebet). `optional_columns` er kolonner der kun
findes i nogle takstsystemers skema.

Arc-designet (drg_noegler_beslutningsnotat.md):
leverance-interne heltals-ID'er og SDS' DW_EK_*/DW_SK_* UDELADES af arc
(ude af sync paa tvaers af tabeller efter merge) — relationer er oploest
til UUID-referencer, der beregnes i ext-views af drg_archive.py.
Undtagelse: psyk DW_EK_Helbredsforloeb beholdes som analytisk attribut
(psyk-skemaet har ingen forloebs-UUID); aldrig join-noegle.

NAVNGIVNING AF ARC-TABELLER (besluttet af Jacob, 2026-08-27): `ext_table`
SPEJLER KILDEN. Derfor `drg_sghforlob` (SDS' fil heder DRGSGHFORLOB, uden
oe) over for `drgpsyk_forloeb` (SDS' fil heder Psyk_forloeb, med oe) — de
to leverancetyper staver forloeb forskelligt hos SDS, og arkivet gengiver
det frem for at normalisere. Eneste bevidste afvigelse er flertal ->
ental (DIAGNOSER -> drg_diagnose), jf. navngivningsstandardens ental-regel.
Normaliseringen af danske ord (oe/aa/ae) hoerer i DSA-laget, ikke her.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class ArcColumn:
    """Kolonne i arc-tabellen: navn, NVARCHAR-bredde og nullability."""

    name: str
    width: int
    nullable: bool = True


@dataclass(frozen=True)
class DrgDataset:
    """Et datasaet i en leverance og dets vej til arc."""

    leverancetype: str  # 'DRG' | 'DRGPSYK'
    source_prefix: str  # filnavns-prefix, fx 'DRGKONTAKT' / 'Psyk_kontakt'
    ext_table: str  # ext.<navn> og arc.<navn>
    source_columns: tuple[str, ...]  # unionen af metadata-kolonner, i kildeorden
    source_widths: dict[str, int] = field(hash=False)
    optional_columns: tuple[str, ...] = ()  # findes kun i nogle takstsystemer
    # Takstsystemer hvor optional_columns LOVLIGT maa mangle. En kolonne der
    # forsvinder fra et nyere takstsystems skema er en regression, der ville
    # NULLe vaerdierne i hele arc via mergen — det skal fejle, ikke passere.
    optional_takstsystemer: tuple[str, ...] = ()
    key_widths: dict[str, int] = field(default_factory=dict, hash=False)
    arc_dropped: tuple[str, ...] = ()  # volatile ID'er/DW-noegler — aldrig i arc
    arc_added: tuple[ArcColumn, ...] = ()  # oploeste UUID-referencer m.m.
    merge_keys: tuple[str, ...] = ()  # + takstsystem; tom => insert_only
    revision_columns: tuple[str, ...] = ()  # prislog i arc.drg_pris_revision
    aktivitetsaar_column: str | None = None  # driver aarsskive-scoped deletes
    insert_only: bool = False

    @property
    def arc_columns(self) -> tuple[str, ...]:
        """Arc-kolonneorden: tilfoejede referencer foerst, saa kildekolonner."""
        kept = tuple(c for c in self.source_columns if c not in self.arc_dropped)
        return tuple(a.name for a in self.arc_added) + kept


