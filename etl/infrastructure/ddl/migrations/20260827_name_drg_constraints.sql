--
-- [internal ticket] (20260825b_name_default_constraints.sql) landed on this branch
-- after the DRG DDL was written. Base DDL in tables/drg/ now declares the
-- names; this migration brings already-deployed databases (where the pipeline
-- has created arc.drg_* / meta.DRGLeverance with autogenerated or old names)
-- to the same names. Fresh databases are a no-op (already correct).
--
-- Same guards as 20260825b: skip missing tables, report missing defaults,
-- no-op when the name already matches (case-sensitive).
-- ============================================================================

