-- profile), so no data is truncated.
--
-- The matching CREATE TABLE statements in tables/erp/00_archive.sql already
-- declare the sized types, so on a fresh install this migration is a no-op. On
-- an existing database it narrows in place. None of these columns take part in
-- a primary key or index, so a plain ALTER COLUMN is sufficient.
--
-- NOTE: narrowing NVARCHAR(MAX) is a size-of-data operation -- on a populated
-- table SQL Server rewrites and logs every row, so run this in a maintenance
-- window, or simply reload the tables from empty (the archive fast-load path
-- recreates them from the sized DDL). Each ALTER is guarded to run only while the
-- column is still wider than its target, so the script is idempotent; missing
-- tables/columns are skipped via the sys.columns join. SET XACT_ABORT ON ensures
-- that if any value would be truncated the ALTER fails atomically rather than
-- silently dropping data.

