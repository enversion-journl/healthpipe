DECLARE @tbl SYSNAME, @col SYSNAME, @len INT, @sql NVARCHAR(MAX);

DECLARE narrow CURSOR LOCAL FAST_FORWARD FOR
    SELECT t.tbl, t.col, t.len
    FROM @target t
    JOIN sys.columns c
      ON c.object_id = OBJECT_ID(N'[arc].[' + t.tbl + N']')
     AND c.name = t.col
    WHERE c.max_length = -1 OR c.max_length > t.len * 2   -- only if still wider than target
    ORDER BY t.tbl, t.col;

OPEN narrow;
FETCH NEXT FROM narrow INTO @tbl, @col, @len;
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @sql = N'ALTER TABLE [arc].' + QUOTENAME(@tbl)
             + N' ALTER COLUMN ' + QUOTENAME(@col)
             + N' NVARCHAR(' + CAST(@len AS NVARCHAR(11)) + N') NULL;';
    EXEC sys.sp_executesql @sql;
    PRINT 'Narrowed ' + @tbl + '.' + @col + ' -> NVARCHAR(' + CAST(@len AS NVARCHAR(11)) + ')';
    FETCH NEXT FROM narrow INTO @tbl, @col, @len;
END
CLOSE narrow;
DEALLOCATE narrow;
GO
