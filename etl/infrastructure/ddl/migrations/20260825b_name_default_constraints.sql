DECLARE @schema SYSNAME, @table SYSNAME, @column SYSNAME, @new SYSNAME;
DECLARE @old SYSNAME, @is_system BIT, @object_id INT, @qualified NVARCHAR(776);
DECLARE @sys_renamed INT = 0, @user_renamed INT = 0, @already INT = 0,
        @absent INT = 0, @no_default INT = 0;

DECLARE default_cursor CURSOR LOCAL FAST_FORWARD FOR
    SELECT schema_name, table_name, column_name, new_name FROM @defaults;

OPEN default_cursor;
FETCH NEXT FROM default_cursor INTO @schema, @table, @column, @new;

WHILE @@FETCH_STATUS = 0
BEGIN
    SELECT @object_id = NULL, @old = NULL, @is_system = NULL;

    SELECT @object_id = t.object_id
    FROM sys.tables t
    JOIN sys.schemas s ON s.schema_id = t.schema_id
    WHERE s.name = @schema AND t.name = @table;

    IF @object_id IS NULL
    BEGIN
        SET @absent = @absent + 1;
    END
    ELSE
    BEGIN
        SELECT @old = dc.name, @is_system = dc.is_system_named
        FROM sys.default_constraints dc
        JOIN sys.columns c ON c.object_id = dc.parent_object_id
                          AND c.column_id = dc.parent_column_id
        WHERE dc.parent_object_id = @object_id AND c.name = @column;

        IF @old IS NULL
        BEGIN
            SET @no_default = @no_default + 1;
            PRINT 'No default constraint to rename: ' + @schema + '.' + @table + '.' + @column;
        END
        ELSE IF @old COLLATE Latin1_General_100_CS_AS = @new COLLATE Latin1_General_100_CS_AS
        BEGIN
            SET @already = @already + 1;
        END
        ELSE
        BEGIN
            SET @qualified = QUOTENAME(@schema) + N'.' + QUOTENAME(@old);
            EXEC sp_rename @qualified, @new, 'OBJECT';
            IF @is_system = 1 SET @sys_renamed  = @sys_renamed  + 1;
            ELSE              SET @user_renamed = @user_renamed + 1;
        END
    END

    FETCH NEXT FROM default_cursor INTO @schema, @table, @column, @new;
END

CLOSE default_cursor;
DEALLOCATE default_cursor;

PRINT 'Default-constraint naming: ' + CAST(@sys_renamed AS NVARCHAR(10))
    + ' system-named renamed, ' + CAST(@user_renamed AS NVARCHAR(10))
    + ' previously-named renamed, ' + CAST(@already AS NVARCHAR(10)) + ' already correct, '
    + CAST(@absent AS NVARCHAR(10)) + ' table(s) not on this database, '
    + CAST(@no_default AS NVARCHAR(10)) + ' column(s) without a default (of 525 known).';
GO
