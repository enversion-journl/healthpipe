-- Give every column DEFAULT constraint a stable, explicit name: DF_<table>_<column>.
--
-- Two separate problems, one fix:
--   1. Most defaults were declared inline and unnamed:
--          [dw_timestamp_insert] DATETIME2(0) NOT NULL DEFAULT SYSDATETIME(),
--      SQL Server then invents a per-database name (DF__ils_vare__dw_ti__1A2B3C4D),
--      so no two databases agree and nothing can reference the constraint by name.
--   2. The handful that WERE named used 33 different conventions
--      (DF_Ref_Patient_Borger_DW_IsDeleted, DF_ifdb_routing_insert,
--      DF_FHIR_Patient_DwIsDeleted, ...).
--
-- ddl/tables/ now declares them as DF_<table>_<column> (525 named defaults in
-- this file's list, including fhir.*.dw_is_deleted), which fixes freshly
-- provisioned databases. This migration brings already-deployed ones to
-- the same names so the two paths converge.
--
-- Databases that already stamped this file before the remaining fhir
-- dw_is_deleted rows were listed (Dev DSA: 2026-08-26, then
-- 20260825_fhir_dw_is_deleted_not_null.sql on 2026-08-27) are brought to the
-- same names by 20260827b_name_fhir_dw_is_deleted_defaults.sql. Editing this
-- file after it is stamped is a no-op.
--
-- Per (schema, table, column), guarded so a re-run is a no-op:
--   * no such table on this database      -> skip (staging/DSO split)
--   * no default constraint on the column -> report, leave alone
--   * constraint already has the new name -> no-op
--   * anything else                       -> sp_rename to the new name
--
-- Only the constraint NAME changes; the default expression is untouched. Some
-- audit columns still read GETDATE() rather than SYSDATETIME() - that difference
-- is deliberately preserved here and left for a separate change.
--
-- Name matching is case-sensitive (Latin1_General_100_CS_AS) so a rename that
-- differs only in case is not mistaken for already-applied. Runs on BOTH staging
-- and DSO via the shared migrations/ directory.
-- ============================================================================

